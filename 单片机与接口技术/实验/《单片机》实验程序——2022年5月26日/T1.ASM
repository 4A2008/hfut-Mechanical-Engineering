	ORG	0000H
	LJMP	MAIN

	ORG	0030H
MAIN:	MOV	SP,#70H
	MOV	P1,#11111111B
	JB	P3.0,$		;P3.0接K7,作为“启动”
AGAIN:	XRL	P1,#11110000B
	CALL	DELAY
	JNB	P3.1,$		;P3.1接K8,作为“暂停”
	XRL	P1,#00001111B
	CALL	DELAY
	JNB	P3.1,$		;P3.1接K8,作为“暂停”
	SJMP	AGAIN

DELAY:	MOV	R5,#02H		;延时
DELAY1:	MOV	R6,#00H	
DELAY2:	MOV	R7,#00H	
	DJNZ	R7,$	
	DJNZ	R6,DELAY2	
	DJNZ	R5,DELAY1	
	RET		
			
	END		
